"""Build reports/report.json and reports/report.html from REAL results.

Inputs (all generated by actually running things):
  reports/junit.xml          <- written by pytest (--junitxml)
  reports/performance.json   <- written by qa.performance benchmarks
  bug_reports/bugs.json      <- written by qa.bug_reporter
  logs/*.log                 <- written by qa.logger

Run:  python -m qa.report_generator
"""

import html
import json
import xml.etree.ElementTree as ET
from datetime import datetime
from pathlib import Path

from qa.bug_reporter import DEFAULT_BUG_FILE, BugReporter
from qa.logger import LOG_DIR, ROOT_DIR
from qa.performance import PERF_FILE, load_benchmarks

REPORT_DIR = ROOT_DIR / "reports"
JUNIT_FILE = REPORT_DIR / "junit.xml"
REPORT_JSON = REPORT_DIR / "report.json"
REPORT_HTML = REPORT_DIR / "report.html"


def parse_junit(junit_path=JUNIT_FILE):
    junit_path = Path(junit_path)
    if not junit_path.exists():
        raise FileNotFoundError(
            f"{junit_path} not found. Run 'python scripts/run_qa.py' or "
            f"'python -m pytest --junitxml=reports/junit.xml' first."
        )
    root = ET.parse(junit_path).getroot()
    total = failed = errors = skipped = 0
    problems = []
    for case in root.iter("testcase"):
        total += 1
        name = f"{case.get('classname', '')}::{case.get('name', '')}"
        failure, error = case.find("failure"), case.find("error")
        if failure is not None:
            failed += 1
            problems.append({"test": name, "type": "failure", "message": (failure.get("message") or "")[:200]})
        elif error is not None:
            errors += 1
            problems.append({"test": name, "type": "error", "message": (error.get("message") or "")[:200]})
        elif case.find("skipped") is not None:
            skipped += 1
    duration = sum(float(s.get("time", 0)) for s in root.iter("testsuite"))
    passed = total - failed - errors - skipped
    return {
        "total": total, "passed": passed, "failed": failed, "errors": errors,
        "skipped": skipped,
        "pass_percentage": round(passed / total * 100, 2) if total else 0.0,
        "duration_seconds": round(duration, 3),
        "problem_tests": problems,
    }


def collect_logs(log_dir=LOG_DIR):
    log_dir = Path(log_dir)
    if not log_dir.exists():
        return []
    return [{"file": f"logs/{p.name}", "size_bytes": p.stat().st_size}
            for p in sorted(log_dir.glob("*.log"))]


def collect_bugs(bug_file=DEFAULT_BUG_FILE):
    bugs = BugReporter(bug_file).list_bugs()
    by_status = {}
    for b in bugs:
        by_status[b["status"]] = by_status.get(b["status"], 0) + 1
    return {"file": "bug_reports/bugs.json", "total": len(bugs),
            "by_status": by_status, "recent": bugs[-5:][::-1]}


def generate_report(junit_path=JUNIT_FILE, perf_path=PERF_FILE, bug_file=DEFAULT_BUG_FILE,
                    log_dir=LOG_DIR, out_json=REPORT_JSON, out_html=REPORT_HTML):
    report = {
        "generated_at": datetime.now().isoformat(timespec="seconds"),
        "summary": parse_junit(junit_path),
        "performance": load_benchmarks(perf_path),
        "bugs": collect_bugs(bug_file),
        "logs": collect_logs(log_dir),
    }
    out_json, out_html = Path(out_json), Path(out_html)
    out_json.parent.mkdir(parents=True, exist_ok=True)
    out_json.write_text(json.dumps(report, indent=2), encoding="utf-8")
    out_html.write_text(render_html(report), encoding="utf-8")
    return report


def print_summary(report):
    s = report["summary"]
    print("=" * 52)
    print(" GameTestPro - Test Execution Summary")
    print("=" * 52)
    print(f" Total: {s['total']}  Passed: {s['passed']}  Failed: {s['failed']}  "
          f"Errors: {s['errors']}  Skipped: {s['skipped']}")
    print(f" Pass rate: {s['pass_percentage']}%   Duration: {s['duration_seconds']}s")
    print(f" Bugs on file: {report['bugs']['total']} {report['bugs']['by_status']}")
    if report["performance"]:
        for r in report["performance"]["results"]:
            print(f" perf {r['operation']:<13} avg={r['average_ms']:.6f} ms over {r['executions']} runs")
    print(f" Reports: {REPORT_JSON.relative_to(ROOT_DIR)} and {REPORT_HTML.relative_to(ROOT_DIR)}")
    print("=" * 52)


# ---------------------------------------------------------------- HTML
CSS = """
body{font-family:Arial,sans-serif;margin:24px;background:#f4f6f8;color:#222}
h1{margin-bottom:0} .sub{color:#666;margin-top:4px}
.cards{display:flex;gap:12px;flex-wrap:wrap;margin:20px 0}
.card{background:#fff;border-radius:8px;padding:14px 20px;min-width:110px;box-shadow:0 1px 3px #0002}
.card b{display:block;font-size:26px}
.pass b{color:#1a7f37}.fail b{color:#cf222e}
table{border-collapse:collapse;background:#fff;width:100%;margin-bottom:24px}
th,td{border:1px solid #ddd;padding:6px 10px;text-align:left;font-size:14px;vertical-align:top}
th{background:#eaeef2} .note{color:#666;font-size:13px}
"""


def _table(headers, rows):
    head = "".join(f"<th>{html.escape(h)}</th>" for h in headers)
    body = "".join("<tr>" + "".join(f"<td>{html.escape(str(c))}</td>" for c in r) + "</tr>" for r in rows)
    return f"<table><tr>{head}</tr>{body}</table>"


def render_html(report):
    s, bugs = report["summary"], report["bugs"]
    esc = html.escape
    out = ["<!DOCTYPE html><html><head><meta charset='utf-8'><title>GameTestPro Report</title><style>",
           CSS, "</style></head><body>",
           "<h1>GameTestPro Dashboard</h1>",
           f"<p class='sub'>Generated {esc(report['generated_at'])}</p>",
           "<div class='cards'>",
           f"<div class='card'>Total<b>{s['total']}</b></div>",
           f"<div class='card pass'>Passed<b>{s['passed']}</b></div>",
           f"<div class='card fail'>Failed<b>{s['failed'] + s['errors']}</b></div>",
           f"<div class='card'>Skipped<b>{s['skipped']}</b></div>",
           f"<div class='card'>Pass rate<b>{s['pass_percentage']}%</b></div>",
           f"<div class='card'>Duration<b>{s['duration_seconds']}s</b></div></div>"]

    if s["problem_tests"]:
        out.append("<h2>Failed / errored tests</h2>")
        out.append(_table(["Test", "Type", "Message"],
                          [(p["test"], p["type"], p["message"]) for p in s["problem_tests"]]))

    out.append("<h2>Performance (local benchmark)</h2>")
    perf = report["performance"]
    if perf:
        out.append(f"<p class='note'>{esc(perf['note'])} Runs per operation: {perf['runs_per_operation']}.</p>")
        out.append(_table(["Operation", "Executions", "Avg (ms)", "Min (ms)", "Max (ms)", "Total (ms)"],
                          [(r["operation"], r["executions"], r["average_ms"], r["min_ms"],
                            r["max_ms"], r["total_ms"]) for r in perf["results"]]))
    else:
        out.append("<p class='note'>No benchmark data found. Run scripts/run_qa.py.</p>")

    out.append(f"<h2>Recent bug reports ({bugs['total']} total)</h2>")
    if bugs["recent"]:
        out.append(_table(["ID", "Time", "Test", "Severity", "Status", "Actual result"],
                          [(b["bug_id"], b["timestamp"], b["test_case"], b["severity"],
                            b["status"], b["actual_result"][:120]) for b in bugs["recent"]]))
    else:
        out.append("<p class='note'>No bugs recorded.</p>")
    out.append(f"<p class='note'>Full data: <a href='../{esc(bugs['file'])}'>{esc(bugs['file'])}</a></p>")

    out.append("<h2>Logs</h2><ul>")
    for lg in report["logs"]:
        out.append(f"<li><a href='../{esc(lg['file'])}'>{esc(lg['file'])}</a> ({lg['size_bytes']} bytes)</li>")
    out.append("</ul></body></html>")
    return "".join(out)


if __name__ == "__main__":
    print_summary(generate_report())
